package com.nem.icons.utils

import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.net.Uri
import androidx.core.content.FileProvider
import com.nem.icons.domain.model.ExportResult
import com.nem.icons.domain.model.StyledIcon
import java.io.*
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

object ExportUtils {

    private fun getExportDir(context: Context): File {
        val dir = File(context.getExternalFilesDir(null), "exports")
        dir.mkdirs()
        return dir
    }

    fun exportSinglePng(context: Context, icon: StyledIcon): ExportResult {
        return try {
            val dir = getExportDir(context)
            val fileName = "${icon.appName.replace(" ", "_")}_nem.png"
            val file = File(dir, fileName)
            FileOutputStream(file).use { fos ->
                icon.styledBitmap.compress(Bitmap.CompressFormat.PNG, 100, fos)
            }
            ExportResult(success = true, path = file.absolutePath)
        } catch (e: Exception) {
            ExportResult(success = false, error = e.message)
        }
    }

    fun exportZip(context: Context, icons: List<StyledIcon>): ExportResult {
        return try {
            val dir = getExportDir(context)
            val zipFile = File(dir, "nem_icons_${System.currentTimeMillis()}.zip")
            ZipOutputStream(BufferedOutputStream(FileOutputStream(zipFile))).use { zos ->
                icons.forEach { icon ->
                    val entry = ZipEntry("icons/${icon.appName.replace(" ", "_")}.png")
                    zos.putNextEntry(entry)
                    val bos = ByteArrayOutputStream()
                    icon.styledBitmap.compress(Bitmap.CompressFormat.PNG, 100, bos)
                    zos.write(bos.toByteArray())
                    zos.closeEntry()
                }
            }
            ExportResult(success = true, path = zipFile.absolutePath)
        } catch (e: Exception) {
            ExportResult(success = false, error = e.message)
        }
    }

    /**
     * Creates an MTZ archive compatible with Xiaomi/HyperOS theme engine.
     * Structure: icons/<packageName>.png inside a ZIP with a description.xml
     */
    fun exportMtz(context: Context, icons: List<StyledIcon>, themeName: String = "NemTheme"): ExportResult {
        return try {
            val dir = getExportDir(context)
            val mtzFile = File(dir, "${themeName}_${System.currentTimeMillis()}.mtz")
            ZipOutputStream(BufferedOutputStream(FileOutputStream(mtzFile))).use { zos ->

                // description.xml
                val desc = buildMtzDescription(themeName, icons.size)
                zos.putNextEntry(ZipEntry("description.xml"))
                zos.write(desc.toByteArray())
                zos.closeEntry()

                // preview thumbnail (first icon)
                if (icons.isNotEmpty()) {
                    zos.putNextEntry(ZipEntry("preview.png"))
                    val bos = ByteArrayOutputStream()
                    icons.first().styledBitmap.compress(Bitmap.CompressFormat.PNG, 100, bos)
                    zos.write(bos.toByteArray())
                    zos.closeEntry()
                }

                // icons folder
                icons.forEach { icon ->
                    val entry = ZipEntry("icons/${icon.packageName}.png")
                    zos.putNextEntry(entry)
                    val bos = ByteArrayOutputStream()
                    icon.styledBitmap.compress(Bitmap.CompressFormat.PNG, 100, bos)
                    zos.write(bos.toByteArray())
                    zos.closeEntry()
                }
            }
            ExportResult(success = true, path = mtzFile.absolutePath)
        } catch (e: Exception) {
            ExportResult(success = false, error = e.message)
        }
    }

    private fun buildMtzDescription(name: String, iconCount: Int): String = """
<?xml version="1.0" encoding="UTF-8"?>
<theme>
    <name>$name</name>
    <author>Nem Icons</author>
    <version>1.0</version>
    <target>HyperOS</target>
    <iconCount>$iconCount</iconCount>
    <description>Generated by Nem Icons Studio</description>
</theme>
""".trimIndent()

    fun shareFile(context: Context, filePath: String): Intent {
        val file = File(filePath)
        val uri: Uri = FileProvider.getUriForFile(
            context, "${context.packageName}.fileprovider", file
        )
        return Intent(Intent.ACTION_SEND).apply {
            type = if (filePath.endsWith(".png")) "image/png" else "application/zip"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
    }
}
